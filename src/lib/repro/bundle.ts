// Reproducibility bundle shared by every bench tool:
//   figures + data + project + parameters + methods + software metadata,
//   with a SHA-256 manifest, packed as a plain ZIP.
import pkg from '../../../package.json';
import { backend } from '$lib/backend/api';
import { zipStore, type ZipEntry } from './zip';

export interface ReproFile {
  name: string;
  mime: string;
  data: Uint8Array | string;
}

export interface ReproBundleInput {
  tool: string;
  title: string;
  files: ReproFile[];
  parameters?: Record<string, unknown>;
  methods?: string;
  notes?: string;
  project?: unknown;
  author?: string;
  orcid?: string;
}

export interface ReproBundleResult {
  bytes: Uint8Array;
  fileName: string;
  manifest: ReproManifest;
}

interface ManifestFile {
  name: string;
  mime: string;
  bytes: number;
  sha256: string;
}

export interface ReproManifest {
  format: 'SPICE_REPRO';
  version: 1;
  tool: string;
  title: string;
  generatedAt: string;
  software: { name: string; version: string };
  files: ManifestFile[];
}

function encoder() {
  return new TextEncoder();
}

export function sha256Hex(bytes: Uint8Array): Promise<string> {
  return crypto.subtle.digest('SHA-256', bytes).then((digest) => {
    const out = new Uint8Array(digest);
    return Array.from(out, (b) => b.toString(16).padStart(2, '0')).join('');
  });
}

function safeStem(text: string, fallback: string): string {
  const stem = text
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 72);
  return stem || fallback;
}

function uniqueName(name: string, used: Set<string>): string {
  const clean = name.replace(/\\/g, '/').replace(/^\/+/, '') || 'file';
  if (!used.has(clean)) {
    used.add(clean);
    return clean;
  }
  const dot = clean.lastIndexOf('.');
  const base = dot > 0 ? clean.slice(0, dot) : clean;
  const ext = dot > 0 ? clean.slice(dot) : '';
  let i = 2;
  while (used.has(`${base}-${i}${ext}`)) i++;
  const next = `${base}-${i}${ext}`;
  used.add(next);
  return next;
}

function methodsDoc(input: ReproBundleInput, generatedAt: string): string {
  const lines = [
    `# ${input.title}`,
    '',
    `Tool: ${input.tool}`,
    `Generated: ${generatedAt}`,
    `Software: SPICE GUI ${pkg.version}`
  ];
  if (input.author) lines.push(`Author: ${input.author}`);
  if (input.orcid) lines.push(`ORCID: ${input.orcid}`);
  lines.push(
    '',
    '## Methods',
    '',
    input.methods?.trim() ||
      'Processing parameters are recorded in parameters.json. Figure and data files were exported from the same in-memory project state, so the bundle can be regenerated from project.json with the recorded software version.',
    '',
    '## Parameters',
    '',
    '```json',
    JSON.stringify(input.parameters ?? {}, null, 2),
    '```',
    ''
  );
  if (input.notes?.trim()) lines.push('## Notes', '', input.notes.trim(), '');
  return lines.join('\n');
}

function readmeDoc(input: ReproBundleInput, files: string[], generatedAt: string): string {
  return [
    `# ${input.title} — reproducibility bundle`,
    '',
    `Generated by SPICE GUI ${pkg.version} on ${generatedAt}.`,
    '',
    'Files:',
    ...files.map((name) => `- \`${name}\``),
    '',
    'The bundle is self-contained: `project.json` re-opens in the same tool, `parameters.json` records every processing setting, and `methods.md` carries a draft methods paragraph. `manifest.sha256.json` lists the SHA-256 digest of every other file.',
    '',
    'Verify integrity with:',
    '',
    '```bash',
    'shasum -a 256 *',
    '```',
    ''
  ].join('\n');
}

function storedValue(key: string): string | undefined {
  if (typeof localStorage === 'undefined') return undefined;
  const value = localStorage.getItem(key)?.trim();
  return value || undefined;
}

export async function buildReproBundle(input: ReproBundleInput): Promise<ReproBundleResult> {
  const generatedAt = new Date().toISOString();
  input = {
    ...input,
    author: input.author ?? storedValue('spice_author_name'),
    orcid: input.orcid ?? storedValue('spice_orcid')
  };
  const used = new Set<string>();
  const out: ReproFile[] = [];

  for (const file of input.files) {
    out.push({ ...file, name: uniqueName(file.name, used) });
  }
  if (input.project !== undefined) {
    out.push({
      name: uniqueName('project.json', used),
      mime: 'application/json',
      data: JSON.stringify(input.project, null, 2)
    });
  }
  out.push({
    name: uniqueName('parameters.json', used),
    mime: 'application/json',
    data: JSON.stringify({ tool: input.tool, title: input.title, generatedAt, parameters: input.parameters ?? {} }, null, 2)
  });
  out.push({ name: uniqueName('methods.md', used), mime: 'text/markdown', data: methodsDoc(input, generatedAt) });
  out.push({
    name: uniqueName('software.json', used),
    mime: 'application/json',
    data: JSON.stringify(
      {
        name: 'SPICE GUI',
        version: pkg.version,
        platform: typeof navigator !== 'undefined' ? navigator.userAgent : 'unknown',
        locale: typeof document !== 'undefined' ? document.documentElement.lang : undefined,
        generatedAt
      },
      null,
      2
    )
  });

  const entries: ZipEntry[] = [];
  const manifestFiles: ManifestFile[] = [];
  for (const file of out) {
    const bytes = typeof file.data === 'string' ? encoder().encode(file.data) : file.data;
    entries.push({ name: file.name, data: bytes });
    manifestFiles.push({ name: file.name, mime: file.mime, bytes: bytes.length, sha256: await sha256Hex(bytes) });
  }

  const readme = readmeDoc(input, out.map((f) => f.name), generatedAt);
  const readmeName = uniqueName('README.md', used);
  const readmeBytes = encoder().encode(readme);
  entries.push({ name: readmeName, data: readmeBytes });
  manifestFiles.push({
    name: readmeName,
    mime: 'text/markdown',
    bytes: readmeBytes.length,
    sha256: await sha256Hex(readmeBytes)
  });

  const manifest: ReproManifest = {
    format: 'SPICE_REPRO',
    version: 1,
    tool: input.tool,
    title: input.title,
    generatedAt,
    software: { name: 'SPICE GUI', version: pkg.version },
    files: manifestFiles
  };
  const manifestBytes = encoder().encode(JSON.stringify(manifest, null, 2));
  entries.push({ name: 'manifest.sha256.json', data: manifestBytes });

  return {
    bytes: zipStore(entries),
    fileName: `${safeStem(input.title, input.tool)}-repro.zip`,
    manifest
  };
}

export async function saveReproBundle(
  input: ReproBundleInput
): Promise<{ ok: boolean; path?: string; error?: string; canceled?: boolean; fileName: string }> {
  const bundle = await buildReproBundle(input);
  const r = await backend.saveExport(bundle.fileName, bundle.bytes);
  if (r.data?.saved) return { ok: true, path: r.data.path, fileName: bundle.fileName };
  return { ok: false, error: r.error, canceled: !r.error, fileName: bundle.fileName };
}
